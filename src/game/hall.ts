// Сколько гостей за день физически проходит через зал. 22.11, после отката «Трафика» (#292/#293).
//
// Замер в настоящей сцене (#292): на «Супермаркете» утром ждали ~136 гостей, а зашло 43 (предел зала 11),
// на «Универмаге» — 49 при ~300 (предел 13). Гость ходит по залу ~23 с, и больше maxCustomers × 90 / 23 за
// день через зал не проходит, сколько ни зови рекламой. Симулятор этого не знал и считал всех — баланс
// уровней 2–6 был подобран на поток, которого в игре нет.

import { DAY_SECONDS, storeLevel, type StoreState } from './economy';

/** Сколько секунд гость в среднем проводит в зале: от двери, по полкам, через кассу — до выхода. */
export const VISIT_SECONDS = 23;

/** Сколько гостей за день пропускает зал этого помещения. */
export const hallCap = (state: StoreState): number => Math.round((storeLevel(state).maxCustomers * DAY_SECONDS) / VISIT_SECONDS);
