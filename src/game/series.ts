// Серия у кассы: игрок обслуживает покупателей одного за другим, не заставляя ждать, — и с третьего подряд
// каждый оставляет чаевые. До 10.11 «Серия ×N!» была только надписью: росла сама (кассиры тоже считались),
// рвалась от паузы в семь секунд (в пустом ларьке — сама собой) и ничего не давала.
//
// Правила (здесь — только счёт; зал — scenes/shoppers.ts):
// - в серию идёт только то, что пробил сам игрок: за своей кассой или поторопив сменщика касанием;
//   кассиры остальных касс и киоски серию не трогают — ни вверх, ни вниз;
// - покупатель дошёл до кассы, а пробивать его начали не позже SERIES_REACT_MS — серия растёт;
//   заставили ждать дольше — серия начинается заново с этой покупки;
// - кто-то ушёл из очереди, не дождавшись, — серия обнуляется;
// - пустой зал серию не рвёт: наказываем за медлительность, а не за то, что никто не пришёл.
// Чаевые — доля корзины: с SERIES_TIP_FROM-й покупки подряд по SERIES_TIP_STEP, но не больше SERIES_TIP_MAX.
// В симуляторах экономики чаевых нет: это награда за ловкость живого игрока, а не часть базового темпа.

/** С какой покупки подряд идут чаевые. */
export const SERIES_TIP_FROM = 3;
/** Сколько чаевых прибавляет каждая следующая покупка серии (доля корзины). */
export const SERIES_TIP_STEP = 0.02;
/** Потолок чаевых (доля корзины): седьмая покупка подряд и дальше. */
export const SERIES_TIP_MAX = 0.1;
/** Сколько (мс игрового времени) покупатель может простоять у кассы до начала пробивки, чтобы серия не прервалась. */
export const SERIES_REACT_MS = 4000;

/** Серия после очередной покупки, пробитой игроком: reactMs — сколько покупатель ждал у кассы до начала пробивки. */
export const seriesAfter = (series: number, reactMs: number): number => (reactMs <= SERIES_REACT_MS ? Math.max(0, series) + 1 : 1);

/** Доля корзины, которую оставят чаевыми на n-й покупке серии. */
export const seriesTipRate = (n: number): number => (n < SERIES_TIP_FROM ? 0 : Math.min(SERIES_TIP_MAX, SERIES_TIP_STEP * (n - SERIES_TIP_FROM + 1)));

/** Чаевые за n-ю покупку серии с корзины total: целые монеты, и раз уж положены — не меньше одной. */
export function seriesTip(n: number, total: number): number {
  const rate = seriesTipRate(n);
  return rate > 0 && total > 0 ? Math.max(1, Math.round(total * rate)) : 0;
}

/** Серия прервалась обидно — было что терять (уже шли чаевые): об этом стоит сказать игроку. */
export const seriesLost = (before: number, after: number): boolean => before >= SERIES_TIP_FROM && after < before;
