def door():
    """Дверь «Подсобка» 24×46 (в мире 12×23): тёмная деревянная, две филёнки, латунная табличка с биркой ломбарда,
    ручка и порог. Ниже и уже двери туалета (32×48) — служебная; слово «Подсобка» — табличкой сцены над ней."""
    c = Canvas(24, 46)
    c.rect(0, 0, 24, 46, "z")
    c.rect(1, 1, 22, 45, "x")
    c.rect(3, 3, 18, 43, "b")
    c.vline(3, 3, 43, "B")
    c.vline(20, 3, 43, "a")
    # Филёнки.
    for y, h in ((16, 11), (30, 12)):
        c.frame(6, y, 12, h, "a")
        c.hline(7, y + 1, 10, "B")
    # Табличка с биркой: латунь, внутри — жёлтая бирка с дырочкой и ниткой.
    c.rect(6, 5, 12, 8, "y")
    c.frame(6, 5, 12, 8, "a")
    c.hline(7, 6, 10, "Y")
    c.rect(10, 7, 5, 4, "Y")
    c.px(10, 7, "y")
    c.px(11, 8, "k")
    c.line(9, 7, 8, 9, "k")
    # Ручка и замочная скважина.
    c.rect(17, 28, 2, 3, "y")
    c.px(17, 28, "Y")
    c.px(18, 33, "k")
    # Порог.
    c.rect(1, 44, 22, 2, "g")
    c.save("pawn_door")


