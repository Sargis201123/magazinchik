"""Ломбард (src/game/pawnshop.ts): вещи, ценник, дверь «Подсобка» в зале, метка «ждут ответа» и сейф в подвале.

Вещи — 12×12 (в мире 6×6): часы, гитара, велосипед, золотое кольцо, фотоаппарат, телефон; стоят на полках
ломбарда в подвале (art/basement_art.py bsm_pawn) и в руках у гостей.
15.11, автор: «Ломбард тоже мне непонятен — может убрать из меню и в подвале его держать как комнату». Полки
«Разное» на складе больше нет: до подвала у ломбарда дверь «Подсобка» в задней стене зала (scenes/pawnFx.ts).

    python3 art/pawnshop.py
"""

from sprites import Canvas


def watch():
    """Часы на ремешке: золотой ободок, белый циферблат со стрелками, коричневый ремешок сверху и снизу."""
    c = Canvas(12, 12)
    c.rect(4, 0, 4, 3, "b")
    c.rect(4, 9, 4, 3, "b")
    c.ellipse(6, 6, 4, 4, "y")
    c.ellipse(6, 6, 3, 3, "w")
    c.px(6, 4, "k")
    c.px(6, 5, "k")
    c.px(7, 6, "k")
    c.px(4, 5, "Y")
    c.outline("k")
    c.save("pawn_watch")


def guitar():
    """Гитара наискосок: оранжевый корпус-восьмёрка с розеткой, тёмный гриф вверх вправо."""
    c = Canvas(12, 12)
    c.line(6, 6, 10, 1, "x")
    c.line(7, 6, 11, 1, "x")
    c.rect(10, 0, 2, 2, "K")
    c.ellipse(4, 8.5, 3.5, 3.2, "o")
    c.ellipse(6, 6, 2.4, 2.2, "o")
    c.px(4, 8, "k")
    c.px(5, 8, "k")
    c.px(2, 7, "y")
    c.px(3, 10, "B")
    c.outline("k")
    c.save("pawn_guitar")


def bike():
    """Велосипед боком: два колеса с белыми спицами, красная рама, руль и седло."""
    c = Canvas(12, 12)
    # Колёса без общего контура: чёрная шина, светлый обод, ступица — иначе они сливаются с рамой в пятно.
    for cx in (2.5, 9.5):
        c.ellipse(cx, 8.5, 2.6, 2.6, "k")
        c.ellipse(cx, 8.5, 1.6, 1.6, "W")
        c.px(int(cx), 8, "g")
    c.line(2, 8, 5, 5, "R")
    c.line(5, 5, 8, 5, "R")
    c.line(8, 5, 9, 8, "R")
    c.line(5, 5, 6, 8, "R")
    c.line(2, 8, 6, 8, "r")
    c.rect(4, 3, 3, 1, "k")
    c.vline(5, 4, 1, "g")
    c.line(8, 5, 8, 2, "g")
    c.rect(8, 1, 3, 1, "k")
    c.save("pawn_bike")


