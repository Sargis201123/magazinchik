def bike():
    """🚲 велосипед: колёса-кольца, красная рама, руль и седло."""
    c = Canvas(14, 14)
    for cx in (3.5, 10.5):
        c.ellipse(cx, 9.5, 3.4, 3.4, "K")
        c.ellipse(cx, 9.5, 2.2, 2.2, (0, 0, 0, 0))
        c.px(int(cx), 9, "l")
    c.line(4, 9, 7, 9, "R")
    c.line(7, 9, 9, 5, "R")
    c.line(4, 9, 6, 5, "R")
    c.line(6, 5, 9, 5, "R")
    c.line(9, 5, 10, 9, "R")
    c.hline(5, 4, 3, "K")
    c.line(9, 5, 9, 3, "G")
    c.hline(9, 3, 3, "K")
    return c


def cycle():
    """🔄 кольцо-стрелка «по кругу»: разрыв справа сверху и наконечник."""
    c = Canvas(14, 14)
    c.ellipse(7, 7, 5, 5, "U")
    c.ellipse(7, 7, 3.2, 3.2, (0, 0, 0, 0))
    c.rect(8, 1, 5, 5, (0, 0, 0, 0))
    c.hline(8, 6, 5, "U")
    c.hline(9, 5, 3, "U")
    c.px(10, 4, "U")
    c.px(4, 3, "c")
    c.outline("k")
    return c


def draw(rows, extra):
    # Поле в пиксель вокруг, чтобы контур не обрезался у края.
    c = Canvas(14, 14)
    c.stamp(rows, 1, 1)
    c.outline("k")
    if extra:
        c.stamp(extra, 1, 1)
    return c


def main():
    for name, (rows, extra) in ICONS.items():
        assert len(rows) == 12 and all(len(r) == 12 for r in rows), name
        assert not extra or all(len(r) == 12 for r in extra), name
        draw(rows, extra).save(f"ico_{name}")
    bike().save("ico_bike")
    cycle().save("ico_cycle")


if __name__ == "__main__":
    main()
