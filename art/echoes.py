"""«Эхо решений» (src/game/echoes.ts): что герои давних сценок приносят в зал — поднос пирожков из
пекарни Лёши, грамоту от участка у сержанта и открытку класса у Маши. Держат в руках (scenes/echoesFx.ts).

    python3 art/echoes.py
"""

from sprites import Canvas


def echo_pies():
    """Поднос с пирожками 16×10 (в мире 8×5): румяные пирожки горкой, у одного надломлен бок — начинка."""
    c = Canvas(16, 10)
    # Поднос: светлый край, тень снизу.
    c.round_rect(0, 6, 16, 4, "W", r=1)
    c.hline(1, 9, 14, "l")
    # Три пирожка снизу и один сверху: румяная корочка, светлая макушка.
    for x in (1, 6, 11):
        c.ellipse(x + 2, 6, 2.6, 1.8, "y")
        c.hline(x + 1, 5, 3, "Y")
        c.px(x + 2, 7, "o")
    c.ellipse(8.5, 3.5, 2.6, 1.8, "y")
    c.hline(7, 2, 3, "Y")
    # Надломленный — видна капуста.
    c.px(9, 4, "E")
    c.px(10, 4, "e")
    c.outline("k")
    c.save("echo_pies")


def echo_diploma():
    """Грамота в рамке 12×12 (в мире 6×6): деревянная рамка, герб сверху, строчки и красная печать."""
    c = Canvas(12, 12)
    c.rect(0, 0, 12, 12, "a")
    c.frame(0, 0, 12, 12, "x")
    c.hline(1, 1, 10, "B")
    c.rect(2, 2, 8, 8, "N")
    # Герб и заголовок.
    c.px(5, 3, "y")
    c.px(6, 3, "y")
    c.hline(3, 5, 6, "R")
    # Строчки текста.
    c.hline(3, 7, 6, "l")
    c.hline(3, 8, 4, "l")
    # Печать с ленточкой.
    c.px(8, 8, "r")
    c.px(8, 9, "R")
    c.px(9, 9, "r")
    c.outline("k")
    c.save("echo_diploma")


def echo_card():
    """Открытка от класса 12×10 (в мире 6×5): раскрытая, с сердцем и детскими каракулями-подписями."""
    c = Canvas(12, 10)
    # Две створки: левая розовая с сердцем, правая светлая с подписями; сгиб посередине.
    c.rect(0, 0, 6, 10, "s")
    c.rect(6, 0, 6, 10, "N")
    c.vline(6, 1, 8, "P")
    # Сердце на обложке.
    for x in (1, 2, 4):
        c.px(x, 3, "R")
    c.px(3, 3, "s")
    c.hline(1, 4, 4, "R")
    c.hline(2, 5, 2, "R")
    c.px(1, 3, "w")
    # Подписи цветными ручками.
    c.hline(8, 2, 2, "U")
    c.hline(8, 4, 3, "E")
    c.hline(7, 6, 3, "o")
    c.hline(8, 8, 2, "P")
    c.frame(0, 0, 12, 10, "k")
    c.save("echo_card")


def main():
    echo_pies()
    echo_diploma()
    echo_card()


if __name__ == "__main__":
    main()
