"""Воришка по повадкам (src/game/thiefTells.ts, src/scenes/thiefTells.ts): камеры берут подозрительного в рамку.

13.11, автор: «вор подсвечен красным — ловить скучно». Красного контура больше нет; если в зале висят камеры,
то в миг, когда вор оглядывается или прячет товар, вокруг него на мгновение мигает рамка видоискателя с красной
точкой записи, а над головой — значок камеры. Рамка — чтобы было видно, КОГО взяли на запись; значок — чтобы
было понятно, что это камеры (в лёгком режиме остаётся только он).

    python3 art/thief_tells.py
"""

from sprites import Canvas


def tell_cam():
    """Значок камеры над головой: корпус на кронштейне, объектив, красная точка записи. 16×13."""
    c = Canvas(16, 13)
    # Кронштейн сверху (к потолку).
    c.rect(10, 0, 2, 3, "g")
    c.hline(8, 0, 6, "G")
    # Корпус: светлый верх, тень снизу.
    c.round_rect(3, 3, 11, 6, "W", r=1)
    c.hline(4, 3, 9, "w")
    c.hline(4, 8, 9, "l")
    c.rect(12, 4, 1, 4, "l")
    # Объектив слева: тёмное стекло с бликом.
    c.rect(1, 4, 3, 4, "K")
    c.px(1, 5, "c")
    c.px(2, 4, "U")
    # Красная точка записи.
    c.rect(10, 5, 2, 2, "R")
    c.px(10, 5, "s")
    # Подпорка снизу — тень на «стене».
    c.hline(5, 9, 6, "G")
    c.outline("k")
    c.save("tell_cam")


def tell_frame():
    """Рамка видоискателя вокруг человека: четыре уголка и точка записи. 34×46 (в мире — 17×23, человек — 12×18)."""
    w, h = 34, 46
    c = Canvas(w, h)
    arm, th = 8, 2

    def corner(x, y, dx, dy):
        # Уголок: горизонтальная и вертикальная планки толщиной th от точки (x, y) внутрь рамки.
        hx = x if dx > 0 else x - arm + 1
        vy = y if dy > 0 else y - arm + 1
        c.rect(hx, y if dy > 0 else y - th + 1, arm, th, "w")
        c.rect(x if dx > 0 else x - th + 1, vy, th, arm, "w")

    corner(1, 1, 1, 1)
    corner(w - 2, 1, -1, 1)
    corner(1, h - 2, 1, -1)
    corner(w - 2, h - 2, -1, -1)
    # Точка записи у верхнего левого уголка: «идёт запись» (в контуре — видна и на светлом полу).
    c.round_rect(5, 5, 4, 4, "R", r=1)
    c.px(6, 6, "s")
    c.outline("k")
    c.save("tell_frame")


if __name__ == "__main__":
    tell_cam()
    tell_frame()
