"""Активные моменты дня (src/game/moments.ts): банка для чаевых у кассы и разбитая банка варенья.

    python3 art/moments.py   (или вместе со всем: python3 art/sprites.py)
"""

from sprites import Canvas


def tip_jar():
    """Банка для чаевых 16×20 (в мире 8×10): стекло с бликом, внутри монеты горкой, крышки нет —
    сверху торчит бумажка «спасибо»."""
    c = Canvas(16, 20)
    # Стекло: светлые стенки, тёмное горлышко.
    c.round_rect(2, 4, 12, 15, "W", r=2)
    c.rect(4, 2, 8, 3, "W")
    c.rect(3, 6, 10, 12, "w")
    # Монеты горкой: нижние темнее, верхние ярче.
    c.rect(3, 13, 10, 5, "y")
    c.ellipse(8, 12.5, 4.6, 2.2, "Y")
    for x, y in ((4, 15), (7, 14), (10, 16), (6, 17), (11, 13)):
        c.px(x, y, "o")
    c.px(6, 11, "w")
    c.px(9, 12, "w")
    # Купюра-«спасибо» из горлышка.
    c.rect(9, 0, 4, 5, "E")
    c.px(10, 1, "e")
    c.px(11, 3, "e")
    # Блик на стекле.
    c.vline(4, 7, 4, "w")
    c.outline("k")
    c.save("tip_jar")


def jam_splat():
    """Разбитая банка варенья 28×14 (в мире 14×7): красное пятно, осколки стекла и крышка набок."""
    c = Canvas(28, 14)
    c.ellipse(13, 8, 10, 4.2, "r")
    c.ellipse(12, 7.5, 7, 2.8, "R")
    c.ellipse(20, 10, 3, 1.6, "R")
    c.px(9, 6, "s")
    c.px(14, 7, "s")
    # Осколки: светлые треугольники с бликом.
    for x, y in ((6, 5), (17, 6), (11, 10), (22, 7)):
        c.px(x, y, "w")
        c.px(x + 1, y, "W")
        c.px(x, y + 1, "W")
    # Крышка набок.
    c.rect(2, 9, 5, 3, "y")
    c.hline(2, 9, 5, "Y")
    c.outline("k")
    c.save("jam_splat")


def main():
    tip_jar()
    jam_splat()


if __name__ == "__main__":
    main()
